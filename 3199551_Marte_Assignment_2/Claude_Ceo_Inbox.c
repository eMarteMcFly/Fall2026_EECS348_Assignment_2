/* ---------------------------------------------------------------------------
 * Standard library headers.  Only the C standard library is used; no
 * pre-existing heap or priority-queue module is included, as required.
 * (Author-written block.)
 * ------------------------------------------------------------------------- */
#include <stdio.h>      /* printf, fprintf, fopen, fclose, fgetc, stdin       */
#include <stdlib.h>     /* malloc, realloc, free, EXIT_SUCCESS, EXIT_FAILURE  */
#include <string.h>     /* strcmp, strlen, memcpy                             */
#include <ctype.h>      /* isspace, isdigit                                   */

/* ---------------------------------------------------------------------------
 * Compile-time constants.  (Author-written block.)
 * ------------------------------------------------------------------------- */
#define SENDER_COUNT      5   /* how many sender categories the CEO knows about */
#define SENDER_TEXT_LEN  32   /* buffer size for a sender category string       */
#define DATE_TEXT_LEN    11   /* "MM-DD-YYYY" is 10 characters plus the NUL     */
#define INITIAL_CAPACITY  8   /* starting number of slots in the heap's list    */

/* ---------------------------------------------------------------------------
 * The five legal sender categories, written from the highest priority (index 0)
 * to the lowest priority (index SENDER_COUNT - 1).  Keeping them in one table
 * means the priority order is defined in exactly one place, which makes the
 * program easier to maintain.  (Author-written block.)
 * ------------------------------------------------------------------------- */
static const char *const SENDER_NAMES[SENDER_COUNT] = {
    "Boss",             /* read first                                          */
    "Subordinate",      /* read next                                           */
    "Peer",             /* read next                                           */
    "ImportantPerson",  /* read next                                           */
    "OtherPerson"       /* read last                                           */
};

/* ---------------------------------------------------------------------------
 * One email in the CEO's inbox.  (Author-written block.)
 * ------------------------------------------------------------------------- */
typedef struct {
    char  sender[SENDER_TEXT_LEN];  /* sender category exactly as it is printed  */
    char *subject;                  /* subject line, heap allocated, any length  */
    char  date[DATE_TEXT_LEN];      /* date normalized to MM-DD-YYYY for output  */
    long  dateKey;                  /* YYYYMMDD as a number, so dates compare    */
    long  arrival;                  /* order the email was read from the file    */
    int   rank;                     /* priority: 5 for Boss down to 1 for Other  */
} Email;

/* ---------------------------------------------------------------------------
 * The MaxHeap itself: a list (growable array) of emails plus its bookkeeping.
 * For the email stored at index i, its parent is at (i - 1) / 2 and its two
 * children are at 2i + 1 and 2i + 2.  (Author-written block.)
 * ------------------------------------------------------------------------- */
typedef struct {
    Email  *items;      /* the list of emails; items[0] is the highest priority  */
    size_t  count;      /* how many emails are currently stored in the list      */
    size_t  capacity;   /* how many emails the list can hold before it must grow */
} MaxHeap;

